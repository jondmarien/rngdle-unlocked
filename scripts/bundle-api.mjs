/**
 * Bundle each api TypeScript entry into api/_bundles (underscore dir is
 * ignored by Vercel for function discovery, so bundles are not extra routes).
 *
 * On Vercel (VERCEL=1), replace each api handler .ts with a thin @ts-nocheck
 * stub that imports the matching bundle. That:
 * - Keeps the entry paths Vercel already discovered (deleting .ts caused
 *   "File not found")
 * - Avoids re-exporting ./name.js next to name.ts (TS2303 circular alias —
 *   under NodeNext, .js resolves back to .ts)
 * - Lets the Node builder typecheck a 4-line stub instead of the full
 *   server/game graph (each "Using TypeScript" pass becomes cheap)
 *
 * Local bundle:api only writes api/_bundles and leaves sources untouched.
 *
 * Usage: node scripts/bundle-api.mjs
 */
import { build } from 'esbuild';
import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiRoot = join(root, 'api');
const bundlesRoot = join(apiRoot, '_bundles');

/** Ship resvg WASM next to OG fonts so Vercel includeFiles picks it up. */
async function copyResvgWasm() {
  const src = join(
    root,
    'node_modules',
    '@resvg',
    'resvg-wasm',
    'index_bg.wasm',
  );
  const destDir = join(root, 'server', 'assets');
  const dest = join(destDir, 'index_bg.wasm');
  await mkdir(destDir, { recursive: true });
  await copyFile(src, dest);
  console.log('[bundle-api] copied resvg WASM → server/assets/index_bg.wasm');
}

async function collectTsEntries(dir) {
  /** @type {string[]} */
  const out = [];
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    if (ent.name === '_bundles' || ent.name.startsWith('.')) continue;
    const full = join(dir, ent.name);
    if (ent.isDirectory()) {
      out.push(...(await collectTsEntries(full)));
    } else if (ent.isFile() && ent.name.endsWith('.ts')) {
      out.push(full);
    }
  }
  return out;
}

/**
 * @param {string} fromFile
 * @param {string} toFile
 */
function relativeImport(fromFile, toFile) {
  let rel = relative(dirname(fromFile), toFile).replace(/\\/g, '/');
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return rel;
}

async function main() {
  const entries = await collectTsEntries(apiRoot);
  if (entries.length === 0) {
    console.warn('[bundle-api] no api TypeScript entries found');
    return;
  }

  console.log(
    `[bundle-api] bundling ${entries.length} handlers → api/_bundles/…`,
  );
  const started = Date.now();

  await copyResvgWasm();
  await mkdir(bundlesRoot, { recursive: true });

  await build({
    entryPoints: entries,
    outdir: bundlesRoot,
    outbase: apiRoot,
    bundle: true,
    platform: 'node',
    target: 'node20',
    format: 'esm',
    packages: 'external',
    sourcemap: false,
    logLevel: 'warning',
  });

  const rewriteTs =
    process.env.VERCEL === '1' || process.env.BUNDLE_API_REWRITE === '1';
  if (rewriteTs) {
    for (const tsPath of entries) {
      const relTs = relative(apiRoot, tsPath);
      const bundlePath = join(bundlesRoot, relTs.replace(/\.ts$/i, '.js'));
      const spec = relativeImport(tsPath, bundlePath);
      await writeFile(
        tsPath,
        [
          '// @ts-nocheck',
          '// Generated by scripts/bundle-api.mjs - do not edit on Vercel.',
          `import handler from '${spec}';`,
          'export default handler;',
          '',
        ].join('\n'),
        'utf8',
      );
    }
  }

  await writeFile(
    join(bundlesRoot, '.bundled'),
    `bundled ${entries.length} entries at ${new Date().toISOString()}\n`,
    'utf8',
  );

  const rel = entries.map((p) => relative(root, p).replace(/\\/g, '/'));
  console.log(
    `[bundle-api] wrote ${entries.length} bundles under api/_bundles/${rewriteTs ? ' + thin api handler stubs' : ' (kept api handler sources)'} in ${Date.now() - started}ms`,
  );
  for (const r of rel.slice(0, 5)) {
    const out = r.replace(/^api\//, 'api/_bundles/').replace(/\.ts$/, '.js');
    console.log(`  - ${r} → ${out}`);
  }
  if (rel.length > 5) console.log(`  … +${rel.length - 5} more`);
}

main().catch((err) => {
  console.error('[bundle-api] failed', err);
  process.exit(1);
});
