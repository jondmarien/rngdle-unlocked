// TypeScript 7 (native) ships a `tsc` binary but `require("typescript")` only
// exports version metadata — no classic compiler API (ts.sys, createProgram, …).
// Vercel still loads that API to compile api/**/*.ts serverless functions.
//
// This shim keeps the TS 7 `tsc` binary and re-points require("typescript")
// at @typescript/typescript6 (Microsoft's official classic-API package).
const fs = require('node:fs');
const path = require('node:path');

let tsPkgPath;
let t6Path;
try {
  tsPkgPath = require.resolve('typescript/package.json');
  t6Path = require.resolve('@typescript/typescript6');
} catch {
  console.warn(
    '[patch-typescript-api] skip — typescript or @typescript/typescript6 missing',
  );
  process.exit(0);
}

const tsDir = path.dirname(tsPkgPath);
const pkg = JSON.parse(fs.readFileSync(tsPkgPath, 'utf8'));

// Already patched (idempotent)
if (pkg.__rngdleClassicApiShim) {
  process.exit(0);
}

const libDir = path.join(tsDir, 'lib');
fs.mkdirSync(libDir, { recursive: true });
const shimFile = path.join(libDir, 'classic-api-shim.cjs');
fs.writeFileSync(
  shimFile,
  `// generated by scripts/patch-typescript-api.cjs — do not edit\nmodule.exports = require(${JSON.stringify(t6Path)});\n`,
);

const relShim = './lib/classic-api-shim.cjs';
pkg.main = relShim;
pkg.exports = {
  ...(typeof pkg.exports === 'object' && pkg.exports ? pkg.exports : {}),
  '.': {
    require: relShim,
    default: relShim,
  },
  './package.json': './package.json',
};
pkg.__rngdleClassicApiShim = true;

fs.writeFileSync(tsPkgPath, `${JSON.stringify(pkg, null, 4)}\n`);
console.log(
  '[patch-typescript-api] require("typescript") → @typescript/typescript6; tsc remains TypeScript 7 native',
);
